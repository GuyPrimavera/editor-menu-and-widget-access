/* Run only against the disposable site prepared with tests/fixtures/menus.php. */
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
if (process.env.EMWA_TEST_SITE !== '1') throw new Error('Set EMWA_TEST_SITE=1 for a disposable installation.');
const base = process.env.EMWA_TEST_URL || 'http://127.0.0.1:8999';
const user = process.env.EMWA_TEST_USER;
const password = process.env.EMWA_TEST_PASSWORD;
if (!user || !password) throw new Error('Provide disposable admin credentials in EMWA_TEST_USER and EMWA_TEST_PASSWORD.');
const go = (page, url) => page.goto(url, { waitUntil: 'domcontentloaded', timeout: 90000 });
const settingsUrl = (tab = 'roles') => base + '/wp-admin/options-general.php?page=editorMenuWidgetAccess&tab=' + tab + '&role=editor';
let count = 0;
const pass = (message) => { count++; console.log('PASS: ' + message); };
const navigateSave = async (page, label = 'Save Changes') => {
	await Promise.all([
		page.waitForNavigation({ waitUntil: 'domcontentloaded', timeout: 90000 }),
		page.getByRole('button', { name: label, exact: true }).click({ noWaitAfter: true })
	]);
};
const login = async (page, name, passphrase) => {
	await go(page, base + '/wp-login.php');
	await page.locator('#user_login').fill(name);
	await page.locator('#user_pass').fill(passphrase);
	await page.locator('input[name=redirect_to]').evaluate((input, url) => { input.value = url; }, base + '/wp-admin/index.php');
	await Promise.all([page.waitForNavigation({ waitUntil: 'domcontentloaded', timeout: 90000 }), page.locator('#wp-submit').click({ noWaitAfter: true })]);
};
(async () => {
	const browser = await chromium.launch({ headless: true });
	try {
		const context = await browser.newContext({ viewport: { width: 1360, height: 1000 }, ignoreHTTPSErrors: true });
		const page = await context.newPage();
		page.setDefaultTimeout(90000);
		const errors = [];
		page.on('pageerror', error => errors.push(error.message));
		page.on('dialog', dialog => dialog.accept());
		await login(page, user, password);
		await go(page, settingsUrl());
		await page.getByRole('heading', { name: 'Editor Access', exact: true }).waitFor();
		assert.equal(await page.locator('.emwa-edit-form input[name="manifest"]').count(), 1);
		pass('native settings page and signed form render');
		const artifacts = path.join(__dirname, 'artifacts');
		fs.mkdirSync(artifacts, { recursive: true });
		await page.screenshot({ path: path.join(artifacts, 'roles.png'), fullPage: true });
		assert.equal(await page.locator('.emwa-role-picker').count(), 0);
		assert.match(await page.locator('.emwa-summary').first().textContent(), /Effective Appearance permission for sample user/);
		pass('saved role permissions and an actual sample user render in the read-only preview');
		const sourceGrant = await page.locator('input[name="grant_appearance"]').isChecked();
		await go(page, settingsUrl() + '&copy_target=author');
		await page.getByRole('heading', { name: 'Copy this role’s profile' }).waitFor();
		assert.equal(await page.locator('.emwa-summary').last().locator('tbody tr').count(), 5);
		await navigateSave(page, 'Copy reviewed profile');
		assert.match(await page.locator('.notice-success').last().textContent(), /Profile copied/);
		assert.equal(await page.locator('input[name="grant_appearance"]').isChecked(), sourceGrant);
		assert.equal(await page.locator('input[name="selected_roles[]"][value="author"]').isChecked(), false);
		pass('reviewed profile copy preserves the destination role’s selected state');
		await go(page, settingsUrl());
		assert.equal(await page.locator('.emwa-role-card-active').count(), 1);
		assert.equal(await page.locator('.emwa-role-card a').count() > 1, true);
		await page.locator('.emwa-role-card').filter({ hasText: 'Author' }).getByRole('link', { name: 'Edit access' }).click();
		await page.getByRole('heading', { name: 'Appearance permissions for Author' }).waitFor();
		pass('roles are enabled and opened from one clear list');
		await go(page, settingsUrl('menus'));
		const widgets = 'input[name="hidden_appearance[]"][value="widgets"]';
		const menus = 'input[name="hidden_appearance[]"][value="menus"]';
		const fonts = 'input[name="hidden_appearance[]"][value="fonts"]';
		await page.locator(widgets).check();
		await navigateSave(page);
		assert.match(await page.locator('.notice-success').last().textContent(), /Settings saved/);
		assert.equal(await page.locator(widgets).isChecked(), true);
		pass('browser save persists Appearance visibility from Admin Menu');
		const stale = await context.newPage();
		stale.setDefaultTimeout(90000);
		stale.on('dialog', dialog => dialog.accept());
		await go(stale, settingsUrl('menus'));
		const menusWasHidden = await page.locator(menus).isChecked();
		const fontsWasHidden = await page.locator(fonts).isChecked();
		if (menusWasHidden) await page.locator(menus).uncheck(); else await page.locator(menus).check();
		await navigateSave(page);
		if (fontsWasHidden) await stale.locator(fonts).uncheck(); else await stale.locator(fonts).check();
		await navigateSave(stale);
		assert.match(await stale.locator('.notice-error').last().textContent(), /changed since/);
		assert.equal(await stale.locator(fonts).isChecked(), fontsWasHidden);
		assert.equal(await stale.locator(menus).isChecked(), !menusWasHidden);
		pass('stale browser form cannot overwrite a newer save');
		await stale.close();

		await go(page, settingsUrl('menus'));
		assert.ok(await page.locator('.emwa-rules tbody tr').count() > 5);
		assert.match(await page.locator('.emwa-rules').locator('xpath=preceding-sibling::p[1]').textContent(), /saved rules? refer/);
		pass('unavailable-rule count is shown beside the saved catalog');
		const updatesRow = page.locator('.emwa-rules tbody tr').filter({ has: page.locator('label', { hasText: /^Updates$/ }) });
		const postsRow = page.locator('.emwa-rules tbody tr').filter({ has: page.locator('label', { hasText: /^Posts$/ }) });
		const showAll = page.getByRole('checkbox', { name: 'Show all items', exact: true });
		assert.equal(await showAll.isChecked(), false);
		assert.equal(await postsRow.isVisible(), true);
		assert.equal(await updatesRow.isVisible(), false);
		assert.match(await updatesRow.locator('.emwa-role-visibility').textContent(), /Already hidden by role permissions/);
		pass('default menu list excludes administrator-only items and explains role permission exclusions');
		await showAll.check();
		assert.equal(await updatesRow.isVisible(), true);
		assert.equal((await page.locator('.emwa-dirty').textContent()).trim(), '');
		await showAll.uncheck();
		assert.equal(await updatesRow.isVisible(), false);
		await page.locator('#emwa-search').fill('Updates');
		assert.equal(await page.locator('.emwa-rules tr[data-emwa-search]:visible').count(), 0);
		await showAll.check();
		assert.equal(await updatesRow.isVisible(), true);
		await page.locator('#emwa-search').fill('');
		pass('Show all items works with search without marking settings as changed');
		await updatesRow.locator('input[type=checkbox]').check();
		await showAll.uncheck();
		await navigateSave(page);
		assert.equal(await updatesRow.isVisible(), false);
		assert.equal(await updatesRow.locator('input[type=checkbox]').isChecked(), true);
		await page.getByRole('button', { name: 'Show visible items', exact: true }).click();
		assert.equal(await updatesRow.locator('input[type=checkbox]').isChecked(), true);
		await navigateSave(page);
		await showAll.check();
		assert.equal(await updatesRow.locator('input[type=checkbox]').isChecked(), true);
		assert.match(await updatesRow.locator('.emwa-role-visibility').textContent(), /Hidden by Editor Access/);
		await showAll.uncheck();
		pass('filtered rules survive saving and bulk actions affect only visible rows');
		await go(page, settingsUrl('menus').replace('role=editor', 'role=subscriber'));
		assert.equal(await postsRow.isVisible(), false);
		assert.match(await postsRow.locator('.emwa-role-visibility').textContent(), /Already hidden by role permissions/);
		await page.locator('#emwa-role').selectOption('editor');
		await Promise.all([page.waitForNavigation({ waitUntil: 'domcontentloaded' }), page.getByRole('button', { name: 'Switch role', exact: true }).click()]);
		assert.equal(await postsRow.isVisible(), true);
		pass('role switching recomputes availability without needing an account for that role');
		await page.locator('#emwa-search').fill('fixture');
		assert.equal(await page.locator('.emwa-rules tr[data-emwa-search]:visible').count(), 4);
		assert.equal((await page.locator('.emwa-dirty').textContent()).trim(), '');
		await page.locator('#emwa-search').fill('');
		pass('search filters the current menu catalog');
		const alpha = page.locator('.emwa-rules tbody tr').filter({ has: page.locator('label', { hasText: 'Fixture Alpha' }) });
		const group = await alpha.getAttribute('data-emwa-group');
		const child = page.locator('tr[data-emwa-group="' + group + '"][data-emwa-depth="1"] input[type=checkbox]');
		await child.check();
		await navigateSave(page);
		assert.equal(await page.locator('tr[data-emwa-group="' + group + '"][data-emwa-depth="1"] input').isChecked(), true);
		const beta = page.locator('.emwa-rules tbody tr').filter({ has: page.locator('label', { hasText: 'Fixture Beta' }) });
		const betaGroup = await beta.getAttribute('data-emwa-group');
		assert.equal(await page.locator('tr[data-emwa-group="' + betaGroup + '"][data-emwa-depth="1"] input').isChecked(), false);
		pass('same child slug is configured independently under different parents');
		await page.getByRole('checkbox', { name: 'Delayed menu', exact: true }).check();
		await navigateSave(page);
		pass('a menu registered after the plugin callback can be selected for hiding');
		await page.getByRole('button', { name: 'Collapse all', exact: true }).click();
		assert.equal(await page.locator('.emwa-rules tr[data-emwa-depth="1"]:visible').count(), 0);
		await page.getByRole('button', { name: 'Expand all', exact: true }).click();
		assert.ok(await page.locator('.emwa-rules tr[data-emwa-depth="1"]:visible').count() > 0);
		pass('expand/collapse preserves editable rule values');
		await page.screenshot({ path: path.join(artifacts, 'menus.png'), fullPage: true });

		await go(page, settingsUrl('toolbar'));
		const toolbarRow = page.locator('.emwa-rules tbody tr').filter({ hasText: 'Late fixture toolbar node' });
		await toolbarRow.locator('input[type=checkbox]').check();
		await navigateSave(page);
		assert.equal(await toolbarRow.locator('input[type=checkbox]').isChecked(), true);
		pass('late-added toolbar node is discovered and saved');
		await page.screenshot({ path: path.join(artifacts, 'toolbar.png'), fullPage: true });

		await go(page, settingsUrl('help'));
		const [download] = await Promise.all([
			page.waitForEvent('download'),
			page.getByRole('link', { name: 'Export settings', exact: true }).click()
		]);
		const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
		assert.equal(exported.plugin, 'editor-menu-and-widget-access');
		assert.equal(exported.settings.profiles.editor.hidden_appearance.widgets, true);
		pass('export downloads complete, valid settings JSON');
		exported.settings.profiles.editor.hidden_appearance.widgets = false;
		await page.locator('#emwa-import').fill(JSON.stringify(exported));
		await navigateSave(page, 'Import and merge profiles');
		assert.match(await page.locator('.notice-success').last().textContent(), /Settings saved/);
		await go(page, settingsUrl('menus'));
		assert.equal(await page.locator(widgets).isChecked(), false);
		pass('validated browser import applies the requested profile');
		await go(page, settingsUrl('help'));
		await navigateSave(page, 'Restore backup');
		await go(page, settingsUrl('menus'));
		assert.equal(await page.locator(widgets).isChecked(), true);
		pass('backup restore recovers the pre-import settings');

		const nojs = await browser.newContext({ storageState: await context.storageState(), javaScriptEnabled: false, ignoreHTTPSErrors: true });
		const plain = await nojs.newPage();
		plain.setDefaultTimeout(90000);
		await go(plain, base + '/wp-admin/themes.php?page=editorMenuWidgetAccess&tab=adminMenus&role=editor');
		await plain.getByRole('heading', { name: 'Hide admin menu links', exact: true }).waitFor();
		pass('historical Appearance URL and tab bookmarks still work');
		await go(plain, settingsUrl('menus'));
		const plainUpdates = plain.locator('.emwa-rules tbody tr').filter({ has: plain.locator('label', { hasText: /^Updates$/ }) });
		assert.equal(await plainUpdates.isVisible(), false);
		await plain.getByRole('checkbox', { name: 'Show all items', exact: true }).check();
		await Promise.all([plain.waitForNavigation({ waitUntil: 'domcontentloaded' }), plain.getByRole('button', { name: 'Apply view', exact: true }).click()]);
		assert.equal(await plainUpdates.isVisible(), true);
		assert.match(await plainUpdates.locator('.emwa-role-visibility').textContent(), /Already hidden by role permissions/);
		pass('role filtering and Show all items also work without JavaScript');
		await go(plain, settingsUrl('menus'));
		await plain.locator('label').filter({ has: plain.locator(widgets) }).click();
		assert.equal(await plain.locator(widgets).isChecked(), false);
		await navigateSave(plain);
		assert.equal(await plain.locator(widgets).isChecked(), false);
		pass('saving works without JavaScript');
		await nojs.close();

		await go(page, settingsUrl('menus'));
		const payload = await page.locator('.emwa-edit-form').evaluate(form => Object.fromEntries(new FormData(form)));
		delete payload.complete;
		const incomplete = await context.request.post(base + '/wp-admin/admin-post.php', { form: payload });
		assert.match(await incomplete.text(), /form was truncated or incomplete/);
		pass('incomplete form is rejected without changing settings');

		const editorContext = await browser.newContext({ ignoreHTTPSErrors: true });
		const editorPage = await editorContext.newPage();
		editorPage.setDefaultTimeout(90000);
		await login(editorPage, 'emwa-browser-editor', 'emwa-editor-test-only');
		const denied = await editorContext.request.post(base + '/wp-admin/admin-post.php', { form: { action: 'emwa_save', complete: 'yes' } });
		assert.equal(denied.status(), 403);
		pass('Editor cannot save administrator-only configuration');
		const deniedReset = await editorContext.request.post(base + '/wp-admin/admin-post.php', { form: { action: 'emwa_reset_role_permissions', complete: 'yes' } });
		assert.equal(deniedReset.status(), 403);
		pass('Editor cannot reset role capabilities');
		await go(editorPage, base + '/wp-admin/index.php');
		assert.equal(await editorPage.locator('#wp-admin-bar-emwa-late-fixture').count(), 0);
		assert.equal(await editorPage.locator('#toplevel_page_fixture-alpha .wp-submenu a').filter({ hasText: 'Shared fixture child' }).count(), 0);
		assert.equal(await editorPage.locator('#toplevel_page_fixture-beta .wp-submenu a').filter({ hasText: 'Shared fixture child' }).count(), 1);
		assert.equal(await editorPage.locator('#toplevel_page_emwa-delayed-menu').count(), 0);
		pass('actual Editor menus and toolbar apply the saved per-parent rules');
		await editorContext.close();
		await go(page, settingsUrl());
		assert.equal(await page.locator('.emwa-reset-form').count(), 1);
		assert.equal(await page.locator('.notice-warning.inline').count(), 1);
		await navigateSave(page, 'Reset permissions to WordPress defaults');
		assert.match(await page.locator('.notice-success').last().textContent(), /reset to the WordPress default/);
		assert.match(await page.locator('.notice-success').last().textContent(), /Stored Appearance permission:\s*Yes → No/);
		assert.equal(await page.locator('.notice-success a').filter({ hasText: 'View backups' }).count(), 1);
		pass('role reset displays before-and-after permission verification and backup link');
		assert.equal(await page.locator('input[name="grant_appearance"]').isChecked(), false);
		assert.equal(await page.locator('.notice-warning.inline').count(), 0);
		pass('role reset removes the legacy stored grant and disables the plugin grant');
		await go(page, settingsUrl('help'));
		const [roleBackup] = await Promise.all([
			page.waitForEvent('download'),
			page.getByRole('link', { name: 'Download role permission backups' }).click()
		]);
		const snapshots = JSON.parse(fs.readFileSync(await roleBackup.path(), 'utf8'));
		assert.equal(snapshots.entries[0].role, 'editor');
		assert.equal(snapshots.entries[0].capabilities.edit_theme_options, true);
		pass('role-capability backup is downloadable after reset');
		await go(page, settingsUrl());
		await page.locator('input[name="grant_appearance"]').check();
		await navigateSave(page);
		await page.setViewportSize({ width: 390, height: 844 });
		await go(page, settingsUrl());
		assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
		await page.screenshot({ path: path.join(artifacts, 'mobile.png'), fullPage: true });
		pass('settings layout fits a mobile viewport');
		await go(page, settingsUrl('menus'));
		await page.getByRole('checkbox', { name: 'Show all items', exact: true }).check();
		assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
		await page.screenshot({ path: path.join(artifacts, 'mobile-menus.png'), fullPage: true });
		pass('role visibility labels and the full menu list fit a mobile viewport');
		assert.deepEqual(errors, []);
		pass('settings flows produced no JavaScript exceptions');
		console.log('Completed ' + count + ' browser checks.');
	} finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
